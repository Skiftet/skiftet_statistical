RSpec.describe "SkiftetStatistical::Bandit::Posteriors#rank and #pick pins (0.4.0)" do
  def pins = OrderRulePins

  def lgamma_relative = 1e-9

  def sampler_relative = 1e-12

  # A draw against its pin: a pinned 0.0, 1.0 or infinity exactly, any other within `relative` of the pin.
  def same_draw?(actual, pinned, relative)
    return false unless actual.is_a?(Float)
    return actual.eql?(pinned) if pinned.zero? || pinned == 1.0 || pinned.infinite?

    (actual - pinned).abs / pinned.abs <= relative
  end

  # nil when a replayed record holds its pin by this file's rule, else what moved: the branch, the order, the head,
  # the item, the leader and the draws' items exactly, each draw within `relative`, the next rng.rand exactly.
  def moved(actual, pinned, relative)
    return "#{actual.first(4).inspect}, pinned #{pinned.first(4).inspect}" unless actual.first(4) == pinned.first(4)

    draws = actual[4]
    unless draws.size == pinned[4].size && draws.zip(pinned[4]).all? { |a, p| same_draw?(a, p, relative) }
      return "draws #{draws.inspect}, pinned #{pinned[4].inspect}"
    end
    return nil if actual.size == pinned.size && (actual.size == 5 || actual[5].eql?(pinned[5]))

    "then #{actual[5].inspect}, pinned #{pinned[5].inspect}"
  end

  def each_record
    pins::RECORDED.each do |fixture, operations|
      operations.each do |operation, rules|
        rules.each do |rule, sources|
          sources.each { |source, rows| rows.each { |row| yield fixture, operation, rule, source, row } }
        end
      end
    end
  end

  it "holds a record for every fixture, operation, rule, source and input" do
    expect(pins::RECORDED.keys).to eq(pins::FIXTURES.keys)
    pins::RECORDED.each do |fixture, operations|
      expect(operations.keys).to eq(pins::RULES.keys)
      operations.each do |operation, rules|
        expect(rules.keys).to eq(pins::RULES.fetch(operation).keys)
        rules.each_value do |sources|
          expect(sources.keys).to eq(pins::SOURCES)
          sources.each do |source, rows|
            expect(rows.size).to eq(pins.inputs(fixture, source).size), "#{fixture} #{operation} #{source}"
          end
        end
      end
    end
    each_record do |fixture, operation, rule, source, row|
      label = "#{fixture} #{operation} #{rule} #{source}: #{row.inspect}"
      expect(row.size).to eq(source == :rng ? 6 : 5), label
      expect(row[4]).to all(be_a(Float)), label
      expect(row[3].size).to eq(row[4].size), label
      expect(row[5]).to be_a(Float), label if source == :rng
    end
  end

  it "reaches what each fixture, rule and source is for" do
    pins::RECORDED.each do |fixture, operations|
      operations.each do |operation, rules|
        pins::SOURCES.each do |source|
          rows = rules.values.flat_map { |sources| sources.fetch(source) }
          label = "#{fixture} #{operation} #{source}"
          expect(rows.map(&:first).uniq).to contain_exactly(:thompson, :explored, :shuffled), label
          expect(rows.map { |row| row[2] }).to include(nil), label
          expect(rows.map { |row| row[2] }.compact).not_to be_empty, label
        end
      end
    end
    each_record do |fixture, operation, rule, source, row|
      label = "#{fixture} #{operation} #{rule} #{source}: #{row.inspect}"
      expect(row[3]).to be_empty, label if row[0] == :shuffled
      expect(row[0]).to eq(:thompson), label if rule == :plain
      next unless operation == :rank && rule == :gated

      expect(row[1].size).to eq(3), label
      expect(row[1][1]).to eq("c"), label
    end
    %i[close sparse].each do |fixture|
      draws = pins::RECORDED.fetch(fixture).fetch(:rank).fetch(:plain).fetch(:uniforms).flat_map { |row| row[4] }
      expect(draws).to include(0.0, 1.0), fixture.to_s
    end
  end

  OrderRulePins::RECORDED.each do |fixture, operations|
    operations.each do |operation, rules|
      rules.each do |rule, sources|
        sources.each_key do |source|
          it "#{operation} on #{fixture} under #{rule}, by #{source}, answers as the rule's first build did" do
            relative = source == :rng ? sampler_relative : lgamma_relative
            rows = pins::RECORDED.fetch(fixture).fetch(operation).fetch(rule).fetch(source)
            inputs = pins.inputs(fixture, source)
            changes = inputs.zip(rows).each_with_index.filter_map do |(input, pinned), index|
              change = moved(pins.record(fixture, operation, rule, source, input), pinned, relative)
              "input #{index}: #{change}" unless change.nil?
            end

            expect(changes).to be_empty, "#{changes.size} of #{rows.size} moved; first: #{changes.first(3).join('; ')}"
          end
        end
      end
    end
  end
end
