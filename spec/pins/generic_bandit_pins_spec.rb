RSpec.describe "SkiftetStatistical::Policies::ThompsonSampling pins (0.3.0)" do
  def pins = ThompsonPolicyPins

  def arms_of(fixture)
    fixture[:arms].map { |name, pulls, reward| SkiftetStatistical::Arm.new(name, pulls: pulls, reward_sum: reward) }
  end

  # [ the picks, one ALPHABET character each ("?" for an object not in the list), the next rng.rand ].
  def replay(fixture, seed)
    arms = arms_of(fixture)
    rng = Random.new(seed)
    alpha, beta = fixture[:prior]
    policy = SkiftetStatistical::Policies::ThompsonSampling.new(prior_alpha: alpha, prior_beta: beta, rng: rng)
    picks = Array.new(pins::CALLS) do
      chosen = policy.choose(arms)
      index = arms.index { |arm| arm.equal?(chosen) }
      index ? pins::ALPHABET[index] : "?"
    end
    [ picks.join, rng.rand ]
  end

  it "LO4 holds a record for every fixture and every seed" do
    expect(pins::RECORDED.keys).to eq(pins::FIXTURES.keys)
    pins::RECORDED.each do |name, rows|
      expect(rows.size).to eq(pins::SEEDS.size), "#{name}: #{rows.size} seeds recorded"
      rows.each do |picks, uniform|
        expect(picks.size).to eq(pins::CALLS), "#{name}: #{picks.inspect}"
        expect(uniform).to be_a(Float)
      end
    end
  end

  it "LO4 reaches what each fixture is for" do
    used = pins::RECORDED.transform_values { |rows| rows.flat_map { |picks, _| picks.chars }.uniq.sort }

    expect(used[:ties]).to eq(%w[1 3])
    expect(used[:repeated]).to include("0", "1")
    expect(used[:many].map { |c| pins::ALPHABET.index(c) }.max).to be >= 10
    pins::FIXTURES.each do |name, fixture|
      expect(used[name].map { |c| pins::ALPHABET.index(c) }.max).to be < fixture[:arms].size
      expect(used[name].size).to be > 1, "#{name} picks one arm only"
    end
  end

  ThompsonPolicyPins::FIXTURES.each_key do |name|
    it "LO4 picks what 0.3.0 picked on #{name}, and leaves the stream where 0.3.0 left it" do
      fixture = pins::FIXTURES.fetch(name)
      moved = pins::SEEDS.zip(pins::RECORDED.fetch(name)).filter_map do |seed, (picks, uniform)|
        actual_picks, actual_uniform = replay(fixture, seed)
        next if actual_picks == picks && actual_uniform.eql?(uniform)

        "seed #{seed}: #{actual_picks.inspect} then #{actual_uniform.inspect}, pinned #{picks.inspect} then #{uniform}"
      end

      expect(moved).to be_empty, "#{moved.size} of #{pins::SEEDS.size} seeds moved; first: #{moved.first(3).join('; ')}"
    end
  end
