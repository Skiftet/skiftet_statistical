  # The posterior set a fixture builds.
  def self.set(fixture)
    posteriors = SkiftetStatistical::Bandit::Posteriors
    given = FIXTURES.fetch(fixture)
    if given[:kind] == :beta
      posteriors.beta(given[:pairs], views: given[:views])
    else
      posteriors.normal(given[:pairs], views: given[:views])
    end
  end

  # The inputs of a source, in order: the keys, the given uniforms (UNIFORM_SEEDS' rows, then EDGES), or the seeds.
  def self.inputs(fixture, source)
    items = FIXTURES.fetch(fixture)[:pairs].keys
    case source
    when :key then KEYS
    when :uniforms
      drawn = UNIFORM_SEEDS.map do |seed|
        rng = Random.new(seed)
        explore = rng.rand
        priority = items.to_h { |item| [ item, rng.rand ] }
        { explore: explore, priority: priority, draw: items.to_h { |item| [ item, rng.rand ] } }
      end
      written = EDGES.map do |edge|
        { explore: edge[:explore], priority: items.zip(edge[:priority]).to_h, draw: items.zip(edge[:draw]).to_h }
      end
      drawn + written
    else SEEDS.to_a
    end
  end

  # One call's record: rank's [branch, items, leader, the draws' items, the draws] or pick's [branch, head, item,
  # the draws' items, the draws], the RNG source's followed by the next rng.rand.
  def self.record(fixture, operation, rule, source, input)
    keywords = RULES.fetch(operation).fetch(rule)
    rng = source == :rng ? Random.new(input) : nil
    given = { key: source == :key ? input : nil, uniforms: source == :uniforms ? input : nil, rng: rng }
    set = set(fixture)
    answer = operation == :rank ? set.rank(**given, **keywords) : set.pick(**given, **keywords)
    named = operation == :rank ? [ answer.items.join, answer.leader ] : [ answer.head, answer.item ]
    record = [ answer.branch, *named, answer.draws.keys.join, answer.draws.values ]
    rng.nil? ? record : record << rng.rand
  end

